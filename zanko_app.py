@st.cache_data(ttl=86400, show_spinner=False)
def lookup_branch_phone(branch_name: str) -> str:
    """
    支店名（例：「新宿」「新宿支店」）から三菱UFJ銀行の電話番号を取得する。
    zengin.ajtw.net の全ひらがな頭文字ページを順に検索して支店コードを特定し、
    詳細ページから電話番号を取得する。キャッシュ（24時間）で2回目以降は即時応答。
    Returns: 電話番号文字列（例 "03-3341-9181"）、未検出時は ""
    """
    # 正規化: 末尾の「支店」「出張所」を除いた名称でも検索できるよう準備
    name_clean = branch_name.strip()
    name_bare = name_clean.replace('支店', '').replace('出張所', '').strip()

    # 検索する全ひらがな頭文字（三菱UFJに存在する頭文字を網羅）
    hiragana_chars = list('あいうえおかきくけこさしすせそたちつてとなにのはひふへほまみむめもやゆよらりわ')

    for char in hiragana_chars:
        url = f"https://zengin.ajtw.net/dbs4.php?abg=0005&abs={_url_parse.quote(char)}"
        try:
            with _url_req.urlopen(url, timeout=10) as resp:
                html = resp.read().decode('utf-8')
        except Exception:
            continue

        # 支店名が含まれているか高速チェック
        if name_bare not in html and name_clean not in html:
            continue

        # テーブル行から (支店名, 支店コード) を抽出
        # 典型的なHTML: <td>新宿支店</td>...<td><a href="/dbs5.php?abg=0005&abs=341">詳細情報</a></td>
        rows = _re.findall(r'<tr[^>]*>(.*?)</tr>', html, _re.DOTALL)
        for row in rows:
            cells = _re.findall(r'<td[^>]*>(.*?)</td>', row, _re.DOTALL)
            if not cells:
                continue
            first_cell = _re.sub(r'<[^>]+>', '', cells[0]).strip()
            # 支店名一致チェック（「支店」あり・なし両方）
            cell_bare = first_cell.replace('支店', '').replace('出張所', '').strip()
            if cell_bare != name_bare:
                continue
            # コードを抽出
            code_m = _re.search(r'abs=(\d+)', row)
            if code_m:
                return _fetch_branch_phone_by_code(code_m.group(1))

    return ''


def assemble_address_lines(pct: str, num: str, building: str) -> tuple:
    """
    都道府県〜町名(pct) / 番地(num) / 建物名・部屋番号(building) を
    PDF用の3行タプルに組み立てる。
      line1 = 都道府県　市区町村
      line2 = 町名（複数可）　番地
      line3 = 建物名・部屋番号
    num・building の半角数字・ハイフンは全角に自動変換する。
    """
    _fw = str.maketrans('0123456789-', '０１２３４５６７８９－')
    num_fw = num.strip().translate(_fw).replace('‐', '－')
    bld_fw = building.strip().translate(_fw).replace('‐', '－')

    parts = [p.strip() for p in pct.split('　') if p.strip()]
    if len(parts) >= 3:
        line1 = '　'.join(parts[:2])                                          # 都道府県　市区町村
        line2 = '　'.join(parts[2:] + ([num_fw] if num_fw else []))           # 町名…　番地
    elif len(parts) == 2:
        line1 = '　'.join(parts)
        line2 = num_fw
    elif len(parts) == 1:
        line1 = parts[0]
        line2 = num_fw
    else:
        line1 = ''
        line2 = num_fw
    # 18文字ルール: line2 + 全角スペース + 建物名 が18文字以内なら同一行に結合
    if not bld_fw:
        return (line1, line2, '')
    avail = 18 - len(line2) - 1  # -1 は区切りの全角スペース分
    if avail <= 0:
        # line2 がすでに18文字以上 → 建物名はそのまま line3 へ
        return (line1, line2, bld_fw)
    elif len(bld_fw) <= avail:
        # 建物名が全部入る
        return (line1, line2 + '　' + bld_fw, '')
    else:
        # 一部だけ line2 に入れ、残りを line3 へ
        return (line1, line2 + '　' + bld_fw[:avail], bld_fw[avail:])


def to_fullwidth_postal(s: str) -> str:
    """郵便番号: 半角数字・ハイフンを全角に統一する"""
    return s.translate(str.maketrans('0123456789-', '０１２３４５６７８９－'))


def normalize_phone(s: str) -> str:
    """
    電話番号の書式を統一する。
      - 数字: 全角 → 半角
      - カッコ（丸括弧）: 半角 ( ) → 全角 （ ）
      - ハイフン類: すべて全角 － に統一
    例: ０７７（563）8811 → 077（563）8811
        077(563)-8811    → 077（563）－8811
    """
    # 全角数字 → 半角
    s = s.translate(str.maketrans('０１２３４５６７８９', '0123456789'))
    # カッコは常に半角（全角カッコ → 半角）
    s = s.translate(str.maketrans('（）', '()'))
    # ハイフン類 → 全角ハイフン
    s = s.replace('-', '－').replace('‐', '－').replace('ー', '－')
    return s


def format_address(raw: str) -> tuple:
    """
    住所文字列を解析し、各境界に全角スペースを挿入してPDF用の3行タプルを返す。

    解析順序: 都道府県 → 市区町村（郡含む）→ 町名 → 番地 → 建物名

    例:
        "東京都新宿区西新宿１－１－１新宿マンション１０１"
        → ("東京都　新宿区", "西新宿　１－１－１", "新宿マンション１０１")

    - 既に全角スペースが含まれている場合は整形をスキップし、
      3行に収まるよう分割して返す。
    - 各行は最大約22全角文字を目安とする。

    Returns:
        (line1, line2, line3) のタプル（空行は空文字列）
    """
    s = raw.strip()
    if not s:
        return ("", "", "")

    # 半角数字・ハイフンを全角に統一（部屋番号・番地を含む住所全体）
    s = s.translate(str.maketrans('0123456789-', '０１２３４５６７８９－'))
    s = s.replace('‐', '－')  # Unicode HYPHEN も全角化

    # 既にスペースが入っている場合 → そのまま3行に分割して返す
    if '　' in s:
        parts = s.split('　')
        line1 = '　'.join(parts[:2]) if len(parts) >= 2 else parts[0]
        remaining = parts[2:] if len(parts) > 2 else []
        mid = len(remaining) // 2 + len(remaining) % 2
        line2 = '　'.join(remaining[:mid])
        line3 = '　'.join(remaining[mid:])
        return (line1, line2, line3)

    segments = []

    # ① 都道府県
    m = _re.match(r'^(.*?[都道府県])(.*)', s)
    if not m:
        return (s, "", "")
    segments.append(m.group(1))
    rest = m.group(2)

    # ② 郡（オプション） + 市区町村
    m = _re.match(r'^((?:.*?郡)?.*?[市区町村])(.*)', rest)
    if not m:
        return ('　'.join(segments) + rest, "", "")
    segments.append(m.group(1))
    rest = m.group(2)

    # ③ 町名（数字の直前まで）
    m = _re.match(r'^(.*?)([０-９0-9].*)$', rest, _re.DOTALL)
    if not m:
        # 数字がない → 残りはすべて町名
        return ('　'.join(segments[:2]), rest, "")
    town = m.group(1)
    rest = m.group(2)

    # ④ 番地（数字・全角ハイフン・丁目番地号の の連続）
    m = _re.match(
        r'^([０-９0-9][０-９0-9－\-ー丁目番地号の]*'
        r'(?:[０-９0-9][０-９0-9－\-ー丁目番地号の]*)*)(.*)?$',
        rest,
    )
    if not m:
        num, building = rest, ""
    else:
        num = m.group(1)
        building = (m.group(2) or "").strip()

    # 町名の中に建物名キーワードがあれば分離する
    # 例: "西新宿新宿マンション" → town_real="西新宿", pre_num_building="新宿マンション"
    town_real, pre_num_building = _split_town_building(town)

    # 行を組み立て
    line1 = '　'.join(segments[:2])                              # 都道府県　市区町村
    line2_parts = (
        ([town_real] if town_real else [])
        + ([pre_num_building] if pre_num_building else [])
        + ([num] if num else [])
    )
    line2 = '　'.join(line2_parts)                               # 町名　建物名（前）　番地
